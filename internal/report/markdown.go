// Generate generates a Markdown CR description
func (mr *MarkdownReporter) Generate(result *model.ImpactResult) (string, error) {
	// Create template with helper functions
	tmpl, err := template.New("cr").Funcs(template.FuncMap{
		"uniqueFiles":          uniqueFiles,
		"generateTestCommands": generateTestCommands,
		"isEmptySurfaceDiff":   isEmptySurfaceDiff,
		"formatCallPath":       formatCallPath,
		"noiseFilteredCount":   noiseFilteredCount,
	}).Parse(mr.templateStr)
	if err != nil {
		return "", fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, result); err != nil {
		return "", fmt.Errorf("failed to execute template: %w", err)
	}

	return strings.TrimSpace(buf.String()), nil
}

// uniqueFiles extracts unique file paths from changes
func uniqueFiles(changes []*model.ChangeImpact) []string {
	seen := make(map[string]bool)
	var files []string
	for _, change := range changes {
		if change.Change == nil {
			continue
		}
		if change.Change.Symbol != nil {
			file := change.Change.Symbol.File
			if !seen[file] {
				seen[file] = true
				files = append(files, file)
			}
		} else if change.Change.File != "" && !seen[change.Change.File] {
			seen[change.Change.File] = true
			files = append(files, change.Change.File)
		}
	}
	return files
}

func noiseFilteredCount(changes []*model.ChangeImpact) int {
	count := 0
	for _, change := range changes {
		if change != nil && change.Change != nil && change.Change.NoiseFiltered {
			count++
		}
	}
	return count
}

// generateTestCommands generates executable test commands by language
func generateTestCommands(tests []*model.Symbol) []string {
	if len(tests) == 0 {
		return nil
	}

	// Group tests by language
	testsByLang := make(map[model.Language][]*model.Symbol)
	for _, test := range tests {
		testsByLang[test.Language] = append(testsByLang[test.Language], test)
	}

	var commands []string

	// Generate command for each language
	for lang, langTests := range testsByLang {
		switch lang {
		case model.LanguageGo:
			cmd := generateGoTestCommand(langTests)
			if cmd != "" {
				commands = append(commands, cmd)
			}

		case model.LanguageJava:
			cmd := generateJavaTestCommand(langTests)
			if cmd != "" {
				commands = append(commands, cmd)
			}

		case model.LanguageJavaScript, model.LanguageTypeScript:
			cmd := generateJSTestCommand(langTests)
			if cmd != "" {
				commands = append(commands, cmd)
			}
		}
	}

	return commands
}

func generateGoTestCommand(tests []*model.Symbol) string {
	// Group by package/directory
	packages := make(map[string][]string)
	for _, test := range tests {
		pkg := filepath.Dir(test.File)
		packages[pkg] = append(packages[pkg], test.Name)
	}

	// Build package paths
	var pkgPaths []string
	for pkg := range packages {
		pkgPaths = append(pkgPaths, "./"+pkg)
	}

	// Build test name pattern
	var testNames []string
	for _, pkgTests := range packages {
		testNames = append(testNames, pkgTests...)
	}

	if len(testNames) > 0 {
		pattern := "^(" + strings.Join(testNames, "|") + ")$"
		return fmt.Sprintf("go test -run '%s' %s", pattern, strings.Join(pkgPaths, " "))
	}
	return fmt.Sprintf("go test %s", strings.Join(pkgPaths, " "))
}

func generateJavaTestCommand(tests []*model.Symbol) string {
	// Group test classes
	var classNames []string
	seen := make(map[string]bool)
	for _, test := range tests {
		// Extract class name from file path
		base := filepath.Base(test.File)
		className := strings.TrimSuffix(base, filepath.Ext(base))
		if !seen[className] {
			classNames = append(classNames, className)
			seen[className] = true
		}
	}

	return fmt.Sprintf("mvn test -Dtest=%s", strings.Join(classNames, ","))
}

func generateJSTestCommand(tests []*model.Symbol) string {
	// Group test files
	var testFiles []string
	seen := make(map[string]bool)
	for _, test := range tests {
		if !seen[test.File] {
			testFiles = append(testFiles, test.File)
			seen[test.File] = true
		}
	}

	return fmt.Sprintf("npx jest %s", strings.Join(testFiles, " "))
}

// isEmptySurfaceDiff checks if a contract diff is empty
func isEmptySurfaceDiff(diff *model.ContractDiff) bool {
	if diff == nil {
		return true
	}
	return diff.IsEmpty()
}

// formatCallPath formats a call path for display
func formatCallPath(path []*model.Symbol) string {
	if len(path) == 0 {
		return ""
	}
	var names []string
	for _, sym := range path {
		names = append(names, sym.Name)
	}
	return strings.Join(names, " → ")
}
